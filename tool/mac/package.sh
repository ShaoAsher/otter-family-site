#!/usr/bin/env bash
# 水獭家族 macOS App 共用打包：出 DMG（.app + Applications 快捷方式）与 ZIP。
# 在 App 根目录执行（App 的 tool/package.sh 会转到这里），名称、包标识等读 App 的 otter.json 的 mac 段。
#
# 用法：
#   ./tool/package.sh                # 打 macOS release DMG + ZIP
#   ./tool/package.sh --skip-build   # 跳过编译，仅重新打包已有 Release
#   ./tool/package.sh --zip-only     # 只出 ZIP，不造 DMG
#   ./tool/package.sh --notarize     # Developer ID 签名 + Apple 公证（需已 store-credentials）
#   ./tool/package.sh --keep-old     # 不清理 dist 旧产物（默认公证成功后只留本次最新 DMG/ZIP）
#
# 编译前先按 otter.json 拉表情包（tool/assets.py pull）；公证相关环境变量见 notarize.sh。

set -euo pipefail

ROOT="$PWD"
HERE="$(cd "$(dirname "$0")" && pwd)"
FAMILY="$(cd "$HERE/../.." && pwd)"
[[ -f "$ROOT/otter.json" && -f "$ROOT/pubspec.yaml" ]] || {
  echo "要在 App 根目录执行（需要 otter.json 与 pubspec.yaml）：$ROOT" >&2
  exit 1
}
cfg() { python3 -c 'import json,sys; print(json.load(open("otter.json"))["mac"].get(sys.argv[1], ""))' "$1"; }

APP_NAME="$(cfg bundle)"
BUNDLE_ID="$(cfg bundle_id)"
TITLE="$(cfg title)"
REQUIRES="$(cfg requires)"
SLUG="$(cfg artifact | tr '[:upper:]' '[:lower:]')"
VERSION="$(awk '/^version:/ {print $2; exit}' pubspec.yaml | tr -d '"' | cut -d+ -f1)"
BUILD_TIME="$(date +%Y%m%d-%H%M)"
DIST_DIR="$ROOT/dist"
SKIP_BUILD=0
ZIP_ONLY=0
NOTARIZE=0
KEEP_OLD=0
NOTARIZE_SH="$HERE/notarize.sh"

for arg in "$@"; do
  case "$arg" in
    --skip-build) SKIP_BUILD=1 ;;
    --zip-only) ZIP_ONLY=1 ;;
    --notarize) NOTARIZE=1 ;;
    --keep-old) KEEP_OLD=1 ;;
    -h|--help)
      sed -n '2,12p' "$0"
      exit 0
      ;;
    *)
      echo "未知参数: $arg" >&2
      exit 1
      ;;
  esac
done

need() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "缺少命令: $1" >&2
    exit 1
  }
}

need flutter
need ditto
need hdiutil
if [[ "$NOTARIZE" -eq 1 ]]; then
  need codesign
  need xcrun
fi

HOST_ARCH="$(uname -m)"
# Apple Silicon 报告为 arm64；部分环境为 ARM64
case "$HOST_ARCH" in
  arm64|ARM64) BUILD_ARCH="arm64"; EXCLUDE_ARCH="x86_64" ;;
  x86_64) BUILD_ARCH="x86_64"; EXCLUDE_ARCH="arm64" ;;
  *) BUILD_ARCH="$HOST_ARCH"; EXCLUDE_ARCH="" ;;
esac

# 写入 Release 架构覆盖（避免 macOS 26 lipo 多架构校验失败）
ARCH_CFG="$ROOT/macos/Runner/Configs/PackageArch.xcconfig"
{
  echo "// Generated by tool/package.sh — do not commit."
  echo "ARCHS = ${BUILD_ARCH}"
  echo "ONLY_ACTIVE_ARCH = YES"
  if [[ -n "$EXCLUDE_ARCH" ]]; then
    echo "EXCLUDED_ARCHS = ${EXCLUDE_ARCH}"
  fi
} > "$ARCH_CFG"

cleanup_arch_cfg() {
  rm -f "$ARCH_CFG"
}
trap cleanup_arch_cfg EXIT

echo "==> ${TITLE} 版本 $VERSION · $BUILD_TIME"
echo "==> 工程 $ROOT"
echo "==> 打包架构 ${BUILD_ARCH} (host $(uname -m))"
if [[ "$NOTARIZE" -eq 1 ]]; then
  echo "==> 将签名并公证（Developer ID）"
fi

if [[ "$SKIP_BUILD" -eq 0 ]]; then
  echo "==> 表情包"
  python3 "$FAMILY/tool/assets.py" pull "$ROOT"
  echo "==> flutter pub get"
  flutter pub get
  # 清掉过期的 Swift Explicit Modules 缓存，避免刷屏
  #「*.pcm: No such file or directory」红字警告（不影响产物）。
  rm -rf \
    "$ROOT/build/macos/Build/Intermediates.noindex/SwiftExplicitPrecompiledModules" \
    "$ROOT/build/macos/SDKExplicitPrecompiledModules" \
    2>/dev/null || true
  echo "==> flutter build macos --release"
  flutter build macos --release
else
  echo "==> 跳过编译（--skip-build）"
fi

APP_SRC="$ROOT/build/macos/Build/Products/Release/${APP_NAME}.app"
if [[ ! -d "$APP_SRC" ]]; then
  echo "找不到应用包: $APP_SRC" >&2
  echo "请先成功执行 flutter build macos --release" >&2
  exit 1
fi

# 暂存目录放系统临时目录（不放 dist/）：.app 有数百个文件，
# 结束时的批量删除在部分环境会被 safe-delete 钩子拦截导致脚本中止；
# 临时目录由系统自动回收，失败残留也不污染 dist。
STAGE="$(mktemp -d "${TMPDIR:-/tmp}/${SLUG}-stage.XXXXXX")"
mkdir -p "$DIST_DIR"

echo "==> 复制 ${APP_NAME}.app"
ditto "$APP_SRC" "$STAGE/${APP_NAME}.app"

# 去掉隔离扩展属性，方便本机自测 / 后续 codesign。
xattr -cr "$STAGE/${APP_NAME}.app" 2>/dev/null || true

STAGE_APP="$STAGE/${APP_NAME}.app"

if [[ "$NOTARIZE" -eq 1 ]]; then
  # 先签并公证 .app（stapler 钉在 app 上），再打 ZIP/DMG。
  bash "$NOTARIZE_SH" "$STAGE_APP"
fi

REQUIRES_LINE=""
[[ -n "$REQUIRES" ]] && REQUIRES_LINE="3. ${REQUIRES}"

# 安装说明（放进 DMG / ZIP）
if [[ "$NOTARIZE" -eq 1 ]]; then
  cat > "$STAGE/安装说明.txt" <<EOF
${TITLE}  ${VERSION}

安装步骤
1. 将「${APP_NAME}.app」拖到「应用程序」文件夹
2. 双击打开即可（已 Developer ID 签名并经 Apple 公证）
${REQUIRES_LINE}

系统要求：macOS 12+ (当前安装包架构: ${BUILD_ARCH})
包标识：${BUNDLE_ID}

说明：因系统 lipo 限制，此包为单架构构建（与打包机 CPU 一致）。
Apple Silicon 包请在 M 系列 Mac 上打开；Intel 包请在 Intel Mac 上打包。
EOF
else
  cat > "$STAGE/安装说明.txt" <<EOF
${TITLE}  ${VERSION}

安装步骤
1. 将「${APP_NAME}.app」拖到「应用程序」文件夹
2. 首次打开若提示「无法验证开发者」：
   - 右键应用 → 打开 → 仍要打开
   - 或在「系统设置 → 隐私与安全性」里点允许
   - 或终端执行：
     xattr -cr "/Applications/${APP_NAME}.app"
${REQUIRES_LINE}

系统要求：macOS 12+ (当前安装包架构: ${BUILD_ARCH})
包标识：${BUNDLE_ID}

说明：因系统 lipo 限制，此包为单架构构建（与打包机 CPU 一致）。
Apple Silicon 包请在 M 系列 Mac 上打开；Intel 包请在 Intel Mac 上打包。
未公证包请使用：./tool/package.sh --notarize
EOF
fi

ZIP_NAME="${APP_NAME}-${VERSION}-macos-${BUILD_ARCH}-${BUILD_TIME}.zip"
ZIP_PATH="$DIST_DIR/$ZIP_NAME"
echo "==> 生成 ZIP: $ZIP_PATH"
rm -f "$ZIP_PATH"
(
  cd "$STAGE"
  zip -qry "$ZIP_PATH" "${APP_NAME}.app" "安装说明.txt"
)

DMG_PATH=""
if [[ "$ZIP_ONLY" -eq 0 ]]; then
  DMG_NAME="${APP_NAME}-${VERSION}-macos-${BUILD_ARCH}-${BUILD_TIME}.dmg"
  DMG_PATH="$DIST_DIR/$DMG_NAME"
  VOL_NAME="${APP_NAME} ${VERSION}"
  echo "==> 生成 DMG: $DMG_PATH"

  # 临时只读卷内容：App + Applications 链接 + 说明（也在系统临时目录）
  DMG_STAGE="$(mktemp -d "${TMPDIR:-/tmp}/${SLUG}-dmg.XXXXXX")"
  ditto "$STAGE_APP" "$DMG_STAGE/${APP_NAME}.app"
  cp "$STAGE/安装说明.txt" "$DMG_STAGE/安装说明.txt"
  ln -sf /Applications "$DMG_STAGE/Applications"

  rm -f "$DMG_PATH"
  hdiutil create \
    -volname "$VOL_NAME" \
    -srcfolder "$DMG_STAGE" \
    -ov \
    -format UDZO \
    -fs HFS+ \
    "$DMG_PATH" >/dev/null

  rm -rf "$DMG_STAGE" 2>/dev/null || true

  if [[ "$NOTARIZE" -eq 1 ]]; then
    # 用户下载的是 DMG：再签并公证外层容器。
    bash "$NOTARIZE_SH" "$DMG_PATH"
  fi
fi

# 校验 App 可执行入口
BIN="$STAGE_APP/Contents/MacOS/${APP_NAME}"
if [[ -x "$BIN" ]]; then
  echo "==> 可执行文件 OK: Contents/MacOS/${APP_NAME}"
else
  # Flutter 有时用 PRODUCT_NAME 作为二进制名
  FOUND="$(find "$STAGE_APP/Contents/MacOS" -type f -perm +111 | head -1 || true)"
  echo "==> 可执行文件: ${FOUND:-未找到}"
fi

SIZE_ZIP="$(du -h "$ZIP_PATH" | awk '{print $1}')"
echo ""
echo "打包完成"
echo "  ZIP  $ZIP_PATH  ($SIZE_ZIP)"
if [[ -n "$DMG_PATH" && -f "$DMG_PATH" ]]; then
  SIZE_DMG="$(du -h "$DMG_PATH" | awk '{print $1}')"
  echo "  DMG  $DMG_PATH  ($SIZE_DMG)"
fi
if [[ "$NOTARIZE" -eq 1 ]]; then
  echo ""
  echo "已签名并公证。正式发布：./tool/release.sh --use-dist"
else
  echo ""
  echo "发给别人：优先发 DMG；对方拖到「应用程序」即可。"
  echo "若无法打开：xattr -cr \"/Applications/${APP_NAME}.app\""
  echo "正式分发：./tool/release.sh   （打包+公证+上传到 TOS 与 GitHub）"
fi

# 公证成功后清理 dist：只保留本次最新的 DMG/ZIP，旧版本产物清掉（Windows 包不动）。
# （未公证的构建只用于自测，不动 dist 里已有的正式包。）
if [[ "$NOTARIZE" -eq 1 && "$KEEP_OLD" -eq 0 ]]; then
  echo "==> 清理 dist 旧产物（保留本次构建）"
  shopt -s nullglob
  for f in "$DIST_DIR"/*.dmg "$DIST_DIR"/*.zip; do
    keep=0
    [[ "$f" == *-windows-* ]] && keep=1
    [[ "$f" == "$ZIP_PATH" ]] && keep=1
    [[ -n "$DMG_PATH" && "$f" == "$DMG_PATH" ]] && keep=1
    if [[ "$keep" -eq 0 ]]; then
      echo "    删除 $(basename "$f")"
      rm -f "$f"
    fi
  done
  shopt -u nullglob
fi

# 清理暂存（在系统临时目录，由系统兜底回收；删除失败不阻塞结果）
rm -rf "$STAGE" 2>/dev/null || true
