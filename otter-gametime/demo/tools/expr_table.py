def js_block():
    groups = "var EXPR_GROUPS=[" + ",".join(f"['{k}','{n}']" for k, n in GROUPS) + "];\n"
    rows = [
        f"  {k}:{{n:'{n}', say:'{s}', c:'{r},{g},{b}', g:'{grp}'}}"
        for k, n, s, (r, g, b), grp in EXPR
    ]
    return groups + "var OT_EXPR={\n" + ",\n".join(rows) + "\n};"


def dart_rows():
    return "\n".join(
        f"    GtExpr('{k}', '{n}', '{s}', Color(0xFF{r:02X}{g:02X}{b:02X}), GtExprGroup.{grp}),"
        for k, n, s, (r, g, b), grp in EXPR
    )


def main():
    keys = [e[0] for e in EXPR]
    assert len(keys) == 120 and len(set(keys)) == 120, len(keys)
    js = os.path.join(HERE, "..", "v3.js")
    src = open(js, encoding="utf-8").read()
    a = src.index("var EXPR_GROUPS=")
    b = src.index("\n};", src.index("var OT_EXPR={")) + 3
    open(js, "w", encoding="utf-8").write(src[:a] + js_block() + src[b:])

    dart = os.path.join(HERE, "..", "..", "..", "app", "lib", "ui", "otter", "gt_expr.dart")
    src = open(dart, encoding="utf-8").read()
    a = src.index("  static const all = <GtExpr>[\n") + len("  static const all = <GtExpr>[\n")
    b = src.index("  ];", a)
    open(dart, "w", encoding="utf-8").write(src[:a] + dart_rows() + "\n" + src[b:])
    print(f"OT_EXPR / gt_expr.dart：{len(EXPR)} 条，{len(GROUPS)} 组")


if __name__ == "__main__":
    main()
